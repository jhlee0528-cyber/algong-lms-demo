// 타입별 필터 함수
export const getQuestionsByType = (type: QuizQuestion['type']): QuizQuestion[] => {
  return mockQuestions.filter((q) => q.type === type);
};

// 난이도별 필터 함수
export const getQuestionsByDifficulty = (difficulty: QuizQuestion['difficulty']): QuizQuestion[] => {
  return mockQuestions.filter((q) => q.difficulty === difficulty);
};

// 랜덤 N개 문제 가져오기
export const getRandomQuestions = (count: number, types?: QuizQuestion['type'][]): QuizQuestion[] => {
  let filtered = mockQuestions;
  if (types && types.length > 0) {
    filtered = mockQuestions.filter((q) => types.includes(q.type));
  }

  const shuffled = [...filtered].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, shuffled.length));
};
